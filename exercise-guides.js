  function guide(id, file, target, secondary, steps, breathing, mistakes, alternative, mediaMeta = {}) {
    return { id, file, target, secondary, steps, breathing, mistakes, alternative, ...mediaMeta };
  }

  function strengthGuide(id, file, target, secondary, cue) {
    return guide(id, file, target, secondary, ["先拿轻一点的重量，把身体稳住。", cue, "慢慢回到起点，每一下都走同一条路。"], "用力时呼气，回来时吸气。别急着抢下一下。", ["身体跟着乱晃：重量轻一点，速度慢一点。", "动作越做越大：只做到你能稳稳控制的位置。"], "重量减一点，或者换成同部位的徒手版本。" );
  }

  function approximateGuide(id, file, target, secondary, cue) {
    const data = strengthGuide(id, file, target, secondary, cue);
    data.approximate = true;
    return data;
  }

  function normalizeExerciseName(name) {
    return aliases[name] || name || "当前动作";
  }

  function getExerciseGuide(exercise = {}, options = {}) {
    const name = normalizeExerciseName(exercise.name);
    const specific = guides[name];
    const fallback = {
      target: "全身协调",
      secondary: ["核心稳定"],
      steps: [exercise.stance || "先站稳、坐稳，找个舒服的起点。", exercise.firstMove || "第一下慢慢来，先把路线走顺。", "每一下都照着同一条路走；哪里疼，就马上停。"],
      breathing: "用力时呼气，回来时吸气。别憋着，脸会先累红。",
      mistakes: ["冲得太快：慢一点，稳住比做多更重要。", "为了凑次数变形：少做两下也没关系。"],
      alternative: "重量减一点、幅度小一点，先把动作做顺。",
    };
    const data = specific || fallback;
    return {
      name,
      hasSpecificGuide: Boolean(specific),
      memoryCue: memoryCues[name] || "照着图慢慢走一遍，稳住比速度更重要。",
      target: data.target,
      secondary: data.secondary,
      steps: data.steps,
      breathing: data.breathing,
      mistakes: data.mistakes,
      alternative: data.alternative,
      media: specific?.file && options.mediaEnabled ? {
        src: MEDIA_BASE + specific.file,
        alt: `${name}动作示范`,
        attribution: specific.attribution || "© Gym visual",
        attributionUrl: specific.attributionUrl ?? ATTRIBUTION_URL,
        approximate: Boolean(specific.approximate),
      } : null,
    };
  }

  function getNextExerciseIndex(currentIndex, total) {
    return Math.min(currentIndex + 1, Math.max(total - 1, 0));
  }

  function adjustRestDuration(seconds, delta) {
    return Math.min(180, Math.max(15, seconds + delta));
  }

  function getRemainingRestSeconds(endAt, now = Date.now()) {
    return Math.max(0, Math.ceil((endAt - now) / 1000));
  }

  return {
    adjustRestDuration,
    getExerciseGuide,
    getNextExerciseIndex,
    getRemainingRestSeconds,
    normalizeExerciseName,
  };
